-- Ticket booking schema. Safe to run on an empty database (used by Docker).

CREATE TABLE IF NOT EXISTS seats (
    seat_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seat_number VARCHAR(10) NOT NULL UNIQUE,
    status      VARCHAR(20) NOT NULL DEFAULT 'AVAILABLE'
                CHECK (status IN ('AVAILABLE', 'HELD', 'BOOKED'))
);

CREATE TABLE IF NOT EXISTS reservations (
    reservation_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        INTEGER NOT NULL,
    seat_id        INTEGER NOT NULL REFERENCES seats (seat_id),
    status         VARCHAR(20) NOT NULL DEFAULT 'HELD'
                   CHECK (status IN ('HELD', 'CONFIRMED', 'EXPIRED', 'CANCELLED')),
    created_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    expires_at     TIMESTAMPTZ NOT NULL
);

-- Safety net: PostgreSQL itself refuses two active reservations for one seat.
CREATE UNIQUE INDEX IF NOT EXISTS one_active_reservation_per_seat
ON reservations (seat_id)
WHERE status IN ('HELD', 'CONFIRMED');

-- Speeds up booking history (GET /bookings/history?user_id=...).
CREATE INDEX IF NOT EXISTS reservations_user_id_idx
ON reservations (user_id);

-- Seed 500 seats: A1 .. A500 (only if the table is empty).
INSERT INTO seats (seat_number)
SELECT 'A' || n
FROM generate_series(1, 500) AS n
WHERE NOT EXISTS (SELECT 1 FROM seats);
